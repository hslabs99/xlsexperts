export function slugFromWixBlogUrl(url: string): string | null {
  try {
    const path = new URL(url).pathname
    const m = path.match(/\/post\/([^/?#]+)/i)
    if (!m?.[1]) return null
    return decodeURIComponent(m[1]).trim().toLowerCase()
  } catch {
    return null
  }
}

/** Unique URL entries with stable sortOrder (first occurrence wins). */
export function getWixBlogSeedEntries(): { url: string; slug: string; sortOrder: number }[] {
  const seen = new Set<string>()
  const out: { url: string; slug: string; sortOrder: number }[] = []
  for (const url of WIX_BLOG_SEED_URLS) {
    const slug = slugFromWixBlogUrl(url)
    if (!slug || seen.has(slug)) continue
    seen.add(slug)
    out.push({ url, slug, sortOrder: out.length })
  }
  return out
}
